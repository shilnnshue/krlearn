# 词条、释义、例句都来自官方词表（KOGL Type 1，署名即可复用）。
# 这批只带官方给的那 1 条例句、没有变位表，作为「广度」补充，和人工编写的
# 315 个精选词（3 条分级例句 + 变位 + 全音频）分开标 src。
NIKL_CSV = os.path.join(os.path.dirname(os.path.abspath(__file__)), "nikl_vocab_zh.csv")
# 官方词性代码 → 中文标签。명/동/형 之外的 9 类以前直接丢掉了，
# 实际副词(부/불)、代名词(대)、数词(수)、依存名词(의)、专有名词(고) 都是常用词，全收。
POS_MAP = {
    "명": "名词", "동": "动词", "형": "形容词",
    "부": "副词", "불": "副词",          # 불 = 그래서/이렇게 这类口语固定说法，按副词用
    "의": "依存名词", "관": "冠形词", "고": "专有名词",
    "대": "代名词", "수": "数词", "감": "感叹词", "보": "补助谓词",
}
# 国语院等级 → TOPIK 语义档位：A 初级 / B 中级 / C 高级
GRADE_TOPIK = {"A": 1, "B": 3, "C": 5}
_have_ko = {w["korean"] for w in words}
_n_nikl = 0
_n_dup = 0
if os.path.exists(NIKL_CSV):
    import csv as _csv
    _seen = set()
    _rows = []
    with open(NIKL_CSV, encoding="utf-8-sig") as _f:
        for _row in _csv.DictReader(_f):
            _ko = _row["word"].strip()
            _pos = POS_MAP.get(_row["pos"], "")
            _zh = _row["meaning"].strip()
            _ex = _row["example_ko"].strip()
            _ez = _row["example_translation"].strip()
            if not _pos or not _ko or not _zh or not _ex:
                continue
            if _ko in _have_ko:          # 精选词已覆盖，保留人工那版（3 条分级例句 + 变位）
                continue
            # 只有「同形 + 同词性 + 同释义」才算重复；있다 的「有 / 待着 / 正在进行」
            # 是三个不同用法，必须各自留一条，靠词性区分。
            _key = (_ko, _pos, _zh)
            if _key in _seen:
                _n_dup += 1
                continue
            _seen.add(_key)
            _g = _row["nikl_grade"][:1] or "A"
            _rows.append((_g, _ko, _zh, _pos, _ex, _ez))
    # A → B → C 排序，让 id 递增顺序跟难度一致
    _rows.sort(key=lambda r: "ABC".index(r[0]) if r[0] in "ABC" else 9)
    for _g, _ko, _zh, _pos, _ex, _ez in _rows:
        words.append({
            "id": "w%04d" % (len(words) + 1), "korean": _ko, "chinese": _zh, "pos": _pos,
            "topik": GRADE_TOPIK.get(_g, 1), "irregular": "none", "src": "nikl",
            "level": _g,
            "examples": [{"ko": _ex, "zh": _ez, "level": 1}],
        })
        _n_nikl += 1
print("国语院全表补入:", _n_nikl, "词（跳过完全重复 %d 条）" % _n_dup)

