# ---- 扩展词库（国立国语院《한국어 학습용 어휘 목록》A 级高频词）----
# 三个模块：名词 / 动词 / 形容词，各带 3 条分级例句。TOPIK 标 2 级，
# 这样只进「TOPIK 初级核心词」词本，不会把「延世韩国语 1」撑变形。
EXT_MODS = ("w_ext_nouns", "w_ext_verbs", "w_ext_adjs")
for _m in EXT_MODS:
    try:
        _mod = __import__(_m)
    except Exception as _e:  # noqa
        print("! 扩展词表未加载:", _m, _e)
        continue
    _lst = getattr(_mod, "NEW", [])
    for _ko, _zh, _pos, _irr, _exs in _lst:
        EXTRA[_ko] = _exs
        W.append((_ko, _zh, _pos, 2, _irr, _exs[0][0], _exs[0][1]))
    print("%s 追加: %d 词" % (_m, len(_lst)))

seen = set()
seen_ko = {}          # 韩文 → 词性，防止同一个词换个中文释义重复入库
words = []
for i, (ko, zh, pos, topik, irr, ex_ko, ex_zh) in enumerate(W):
    key = (ko, zh)
    if key in seen:
        continue
    if seen_ko.get(ko) == pos:      # 同形同词性只留先出现的那条
        continue
    seen.add(key)
    seen_ko.setdefault(ko, pos)
    wid = "w%04d" % (len(words) + 1)
    exs = EXTRA.get(ko)
    if exs:
        examples = [{"ko": a, "zh": b, "level": c} for (a, b, c) in exs]
    else:
        examples = [{"ko": ex_ko, "zh": ex_zh, "level": 1}]
    words.append({
        "id": wid, "korean": ko, "chinese": zh, "pos": pos,
        "topik": topik, "irregular": irr, "src": "", "examples": examples,
    })


