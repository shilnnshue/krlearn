CN_PUNCT = ("。", "？", "！", "…")


def validate():
    errs = []
    seen = {}
    for i, g in enumerate(G):
        tag = "%s(%s)" % (g["form"], g["level"])
        for k in ("form", "level", "cat", "attach", "meaning", "desc"):
            if not str(g.get(k, "")).strip():
                errs.append("%s 缺字段 %s" % (tag, k))
        if g["level"] not in LEVELS:
            errs.append("%s level 非法：%s" % (tag, g["level"]))
        if len(g["ex"]) < 2:
            errs.append("%s 例句少于 2 条" % tag)
        for j, e in enumerate(g["ex"]):
            if len(e) != 2 or not e[0].strip() or not e[1].strip():
                errs.append("%s 第 %d 条例句不完整" % (tag, j + 1))
            elif not e[0].strip().endswith((".", "?", "!")):
                errs.append("%s 第 %d 条韩语例句没加标点：%s" % (tag, j + 1, e[0]))
            elif not re.search(r"[가-힣]", e[0]):
                errs.append("%s 第 %d 条例句里没有韩文：%s" % (tag, j + 1, e[0]))
            elif not re.search(r"[\u4e00-\u9fff]", e[1]):
                errs.append("%s 第 %d 条译文里没有中文：%s" % (tag, j + 1, e[1]))
        key = (g["form"], g["level"])
        if key in seen:
            errs.append("重复条目：%s" % tag)
        seen[key] = i
    return errs


def main():
    errs = validate()
    if errs:
        print("校验失败，共 %d 处：" % len(errs))
        for e in errs:
            print("  - " + e)
        sys.exit(1)

    out = []
    for i, g in enumerate(G):
        out.append(dict(
            id="g%03d" % (i + 1),
            form=g["form"],
            level=g["level"],
            cat=g["cat"],
            attach=g["attach"],
            meaning=g["meaning"],
            desc=g["desc"],
            ex=[{"kr": k, "zh": z} for k, z in g["ex"]],
            note=g["note"],
            cmp=g["cmp"],
        ))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")

    by_level = {}
    by_cat = {}
    for o in out:
        by_level[o["level"]] = by_level.get(o["level"], 0) + 1
        by_cat[o["cat"]] = by_cat.get(o["cat"], 0) + 1
    ex_n = sum(len(o["ex"]) for o in out)

    print("已写出 %s" % OUT.relative_to(ROOT))
    print("  条目 %d 条 / 例句 %d 条 / %.1f KB"
          % (len(out), ex_n, OUT.stat().st_size / 1024))
    print("  分布：" + "  ".join("%s %d" % (k, by_level[k]) for k in LEVELS if k in by_level))
    print("  分类：" + "  ".join("%s %d" % (k, by_cat[k])
                                for k in sorted(by_cat, key=lambda x: -by_cat[x])))


if __name__ == "__main__":
    main()
